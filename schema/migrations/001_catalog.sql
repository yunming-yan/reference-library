-- Authority schema 1. Originals stay byte-for-byte in immutable filesystem objects.
-- Search chunks/postings are derived and may be rebuilt, never preferences/jobs.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE TABLE IF NOT EXISTS rl_schema_migrations(version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS rl_state(
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  generation bigint NOT NULL DEFAULT 0,
  mutation_generation bigint NOT NULL DEFAULT 0,
  cursor_secret bytea NOT NULL,
  maintenance_owner text,
  schema_version integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS rl_packages(
  package_id text PRIMARY KEY,
  source_sha text NOT NULL,
  content_sha text,
  object_id text NOT NULL,
  manifest_data bytea NOT NULL,
  blocked boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS rl_packages_source_uq ON rl_packages(source_sha);
CREATE UNIQUE INDEX IF NOT EXISTS rl_packages_content_uq ON rl_packages(content_sha) WHERE content_sha IS NOT NULL;
CREATE TABLE IF NOT EXISTS rl_members(
  package_id text NOT NULL REFERENCES rl_packages(package_id) ON DELETE CASCADE,
  member_path text NOT NULL,
  sha256 text,
  byte_size bigint CHECK(byte_size >= 0),
  PRIMARY KEY(package_id,member_path)
);
CREATE TABLE IF NOT EXISTS rl_reports(
  report_id text PRIMARY KEY,
  package_id text NOT NULL REFERENCES rl_packages(package_id) ON DELETE CASCADE,
  record_data bytea NOT NULL,
  title text NOT NULL,
  original_title text NOT NULL,
  category text NOT NULL DEFAULT '',
  category_fold bytea NOT NULL DEFAULT '\x',
  report_date text NOT NULL,
  issue text NOT NULL,
  imported_at text NOT NULL,
  report_generation bigint NOT NULL DEFAULT 1,
  trashed_at text,
  trash_token text,
  metadata_updated_at text,
  purge_pending boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS rl_reports_order ON rl_reports(purge_pending,(trashed_at IS NOT NULL),report_date DESC,issue DESC,imported_at DESC,report_id DESC);
CREATE INDEX IF NOT EXISTS rl_reports_category_order ON rl_reports(category_fold,(trashed_at IS NOT NULL),report_date DESC,issue DESC,imported_at DESC,report_id DESC) WHERE NOT purge_pending;
CREATE INDEX IF NOT EXISTS rl_reports_package ON rl_reports(package_id);
CREATE TABLE IF NOT EXISTS rl_preferences(singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton), settings jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS rl_operations(
  operation_id text PRIMARY KEY,
  kind text NOT NULL,
  state text NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','running','complete','failed','cancelled')),
  payload_data bytea NOT NULL,
  job_id text,
  report_id text,
  package_id text,
  imported_at text,
  trash_at text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rl_operations_identity ON rl_operations(report_id,trash_at,created_at DESC) WHERE kind='purge';
CREATE INDEX IF NOT EXISTS rl_operations_package ON rl_operations(package_id);
CREATE INDEX IF NOT EXISTS rl_operations_job ON rl_operations(job_id,kind,created_at);
CREATE INDEX IF NOT EXISTS rl_operations_pending ON rl_operations(kind,created_at) WHERE state='pending';
CREATE TABLE IF NOT EXISTS rl_jobs(
  job_id text PRIMARY KEY,
  kind text NOT NULL,
  package_id text,
  state text NOT NULL DEFAULT 'queued',
  phase text NOT NULL DEFAULT 'queued',
  progress double precision NOT NULL DEFAULT 0 CHECK(progress>=0 AND progress<=1),
  message text NOT NULL DEFAULT '',
  error text,
  error_data bytea,
  result_data bytea,
  cancel_requested boolean NOT NULL DEFAULT false,
  payload_data bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rl_jobs_package ON rl_jobs(package_id);
CREATE INDEX IF NOT EXISTS rl_jobs_pending ON rl_jobs(state,created_at);
CREATE TABLE IF NOT EXISTS rl_search_chunks(
  chunk_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id text NOT NULL REFERENCES rl_reports(report_id) ON DELETE CASCADE,
  kind text NOT NULL CHECK(kind IN ('metadata','body')),
  ordinal integer NOT NULL,
  original_start bigint NOT NULL,
  raw_text bytea NOT NULL,
  folded_text bytea NOT NULL,
  index_text text NOT NULL,
  has_nul boolean NOT NULL DEFAULT false,
  UNIQUE(report_id,kind,ordinal)
);
CREATE INDEX IF NOT EXISTS rl_chunks_report ON rl_search_chunks(report_id,kind,ordinal);
CREATE INDEX IF NOT EXISTS rl_chunks_trgm ON rl_search_chunks USING gin(index_text gin_trgm_ops);
CREATE TABLE IF NOT EXISTS rl_short_postings(
  gram bytea NOT NULL,
  chunk_id bigint NOT NULL REFERENCES rl_search_chunks(chunk_id) ON DELETE CASCADE,
  PRIMARY KEY(gram,chunk_id)
);
CREATE INDEX IF NOT EXISTS rl_postings_chunk ON rl_short_postings(chunk_id);



